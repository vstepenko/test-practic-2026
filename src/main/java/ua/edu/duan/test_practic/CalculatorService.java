package ua.edu.duan.test_practic;

public class CalculatorService {
    public int add (int a, int b){
        return a+b ;
    }

    public int cancel (int a, int b){
        return a-b ;
    }

    public int divide (int a, int b){
        return a/b ;
    }

    public int multiply (int a, int b){
        return a*b ;
    }
}
